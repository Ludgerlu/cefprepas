                                                <p style="text-align: justify;">
                                                    L’énergie électrique est au coeur des évolutions énergétiques et des attentes de la société. Les enjeux majeurs du XXIème siècle en termes de changement climatique et de développement
                                                    durable impactent directement les transport (<strong>automobiles, tractions ferroviaires, avions plus électriques etc</strong>.), l&#8217;habitat (
                                                    <strong>optimisation de la distribution électrique grâce à des réseaux intelligents ou smart grids</strong>), l&#8217;économie d’énergie, la production et la distribution d’énergie :
                                                    <strong>intégration des énergies renouvelables, gestion et stabilité des réseaux de distribution, bâtiment et travaux publics habitat, éclairage, voirie, industrie, énergie</strong> etc.
                                                </p>
                                                <p style="text-align: justify;">
                                                    La formation est composée d&#8217;un tronc commun suivi de deux spécialisations (
                                                    <strong>IDEE &#8211; Installation Distribution Énergie Éclairage ou EPRM -Électronique de Puissance Réseaux et Motorisation</strong>) qui permettent d’acquérir des connaissances
                                                    indispensables en électrotechnique dans les domaines liés à l’installation et à la distribution électrique (bâtiment, voirie, éclairage) ou de la conversion d’énergie électrique
                                                    (électronique de puissance, des réseaux et des motorisations).
                                                </p>
