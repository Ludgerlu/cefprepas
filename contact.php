    function enregistrer_js(){	
	var form = document.forms.namedItem("contact_form");			
	var oData = new FormData(form);	
	oData.append("type", "contactForm"); 
	$.ajax({
		url: "actions/add.php",
		type: "POST",
		data: oData,
		processData: false,  
		contentType: false,
		success: function(data){
            console.log(data)
            alert('Merci pour votre message');
			reinitialiser_formulaire_js();
		},
		error: function(xhr, status, error) {
            alert('Une error s\'est produite');
			notification_error_ajax_js(xhr, status, error);
		}
	});
	
}

function reinitialiser_formulaire_js(){	
	document.getElementById("contact-form").reset();
